create table public.categories(name text primary key, created_at timestamptz not null default now());
create table public.products(
 id bigint generated by default as identity primary key,name text not null check(length(name) between 1 and 180),
 category text not null references public.categories(name),code text not null default '',unit text not null default 'item',
 price numeric(12,2) not null check(price>=0),image text not null default '',available boolean not null default true,
 active boolean not null default true,stock integer check(stock>=0),updated_at timestamptz not null default now()
);
create sequence public.store_order_number_seq start 100001;
create table public.orders(
 id uuid primary key default gen_random_uuid(),order_number text not null unique,
 request_id uuid not null unique,request_hash text not null,name text not null,phone text not null,
 fulfilment text not null check(fulfilment in('Pickup','Delivery')),address text not null default '',notes text not null default '',
 status text not null default 'REQUESTED' check(status in('REQUESTED','CONFIRMED','READY','DISPATCHED','COMPLETED','CANCELLED')),
 subtotal numeric(12,2) not null default 0,created_at timestamptz not null default now(),updated_at timestamptz not null default now()
);
create table public.order_items(
 id bigint generated always as identity primary key,order_id uuid not null references public.orders(id) on delete cascade,
 product_id bigint not null references public.products(id),product_name text not null,unit text not null,
 quantity integer not null check(quantity between 1 and 99),unit_price numeric(12,2) not null check(unit_price>=0),
 stock_reserved boolean not null default false,stock_deducted boolean not null default false,unique(order_id,product_id)
);
create table public.checkout_rate_limits(fingerprint text not null,created_at timestamptz not null default now());
create index products_category_idx on public.products(category);
create index orders_created_idx on public.orders(created_at desc);
create index order_items_order_idx on public.order_items(order_id);
create index rate_limit_idx on public.checkout_rate_limits(fingerprint,created_at);
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.checkout_rate_limits enable row level security;
revoke all on public.categories,public.products,public.orders,public.order_items,public.checkout_rate_limits from anon,authenticated;
grant select on public.categories,public.products to anon,authenticated;
create policy categories_read on public.categories for select to anon,authenticated using(true);
create policy active_products_read on public.products for select to anon,authenticated using(active);
grant all on public.categories,public.products,public.orders,public.order_items,public.checkout_rate_limits to service_role;
grant usage,select on all sequences in schema public to service_role;
